      WHERE "AssessmentID" = NEW."AssessmentID" AND "StudentID" = NEW."StudentID"
        AND "ID" <> NEW."ID") >= max_attempts THEN
    RAISE EXCEPTION 'Превышено число попыток: %', max_attempts;
