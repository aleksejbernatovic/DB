    SELECT 1 FROM "Teaches"
    WHERE "GroupDisciplineID" = gd_id AND "TeacherID" = NEW."TeacherID"
  ) THEN
    RAISE EXCEPTION 'Преподаватель не ведёт эту дисциплину у группы';
