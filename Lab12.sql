-- =====================================================================
-- ЗАДАЧА 1. Внесение оценки с автоматическим отчислением
-- =====================================================================
-- Условие. Преподаватель вносит оценку студенту по аттестации (экзамен или зачёт).
-- Если после этого все попытки (MaxAttempts) исчерпаны и ни одна не сдана (оценка < 4),
-- студенту в той же транзакции ставится статус «Отчислен».
-- Обе операции должны выполниться вместе: оценка без отчисления или отчисление без оценки
-- дают противоречивые данные. При ошибке — ROLLBACK, ничего не меняется.
--
-- Пример: студент 201 (Карпович Дмитрий, СДП-ПИ-241), зачёт по «Базам данных» (аттестация 102,
-- MaxAttempts = 2), оценку ставит Пецевич (преподаватель 1). Запустите блок дважды с оценкой 3:
-- после второго раза студент будет отчислен.
--
-- Уровень изоляции: SERIALIZABLE.
-- Решение об отчислении принимается по агрегату (число попыток и наличие положительной
-- оценки) и по значению MaxAttempts из другой таблицы. Такие решения ломаются, если
-- параллельно кто-то меняет прочитанные данные, а строки, которые мы пишем, при этом не
-- пересекаются. Это аномалия write skew / фантомы. Её ловит только SERIALIZABLE.
--
-- Опасные ситуации при более слабом уровне:
-- 1) Две попытки вносятся одновременно (лектор и ассистент на одном зачёте, у студента
--    уже 1 попытка из 2). Каждая транзакция считает попытки, видит 1 < 2 и вставляет свою
--    строку: в итоге 3 попытки при лимите 2. Вставки разных строк не конфликтуют, поэтому
--    READ COMMITTED и REPEATABLE READ это пропускают (фантомное чтение).
-- 2) Деканат одновременно разрешает дополнительную попытку (UPDATE MaxAttempts = 3), а наша
--    транзакция по старому значению 2 решает отчислить. Студента отчисляют, хотя у него
--    ещё есть попытка. Мы MaxAttempts только читаем, конфликта записи нет — на
--    REPEATABLE READ транзакция пройдёт по устаревшему снимку.
-- 3) Параллельно исправляют ошибочно внесённую оценку (UPDATE Grade с 3 на 6). На
--    READ COMMITTED второе чтение в нашей транзакции может увидеть уже другие оценки, чем
--    первое (неповторяющееся чтение): попытки посчитаны по одному состоянию, проверка
--    «есть ли сдача» — по другому, решение об отчислении получается неверным.
-- При SERIALIZABLE во всех трёх случаях одна из транзакций получает ошибку
-- «could not serialize access» и откатывается; её нужно просто повторить.

BEGIN;
SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;

-- 1. Оценка. Триггер проверит: студент из этой группы, преподаватель ведёт дисциплину,
--    попытки не исчерпаны, дата не в прошлом.
INSERT INTO "Attempt" ("AssessmentID", "StudentID", "TeacherID", "Grade", "Date", "Note")
VALUES (102, 201, 1, 3, now()::date, 'Внесено транзакцией лабораторной №12');

-- 2. Отчисление, если попытки кончились и сдачи нет
UPDATE "Student"
SET "StatusID" = (SELECT "ID" FROM "Status" WHERE "Status" = 'Отчислен')
WHERE "StudentID" = 201
  AND (SELECT COUNT(*) FROM "Attempt" WHERE "AssessmentID" = 102 AND "StudentID" = 201)
      >= (SELECT "MaxAttempts" FROM "Assessment" WHERE "ID" = 102)
  AND NOT EXISTS (SELECT 1 FROM "Attempt"
                  WHERE "AssessmentID" = 102 AND "StudentID" = 201 AND "Grade" >= 4);

-- 3. Проверка результата внутри транзакции
SELECT s."StudentID", s."LastName", st."Status",
       (SELECT COUNT(*) FROM "Attempt" WHERE "AssessmentID" = 102 AND "StudentID" = 201) AS attempts
FROM "Student" s JOIN "Status" st ON st."ID" = s."StatusID"
WHERE s."StudentID" = 201;

COMMIT;


-- =====================================================================
-- ЗАДАЧА 2. Перевод студента с дневной формы обучения на заочную
-- =====================================================================
-- Условие. Студента переводят из дневной группы в заочную группу той же специальности
-- и того же курса. При переводе он переходит на платное обучение.
-- Шаги: проверить, что новая группа той же специальности и курса и что студент сейчас
-- в старой группе; удалить его из старой группы; добавить в новую; сменить финансирование.
-- Если любой шаг не прошёл — откат, студент остаётся в старой группе на старых условиях.
-- Без транзакции сбой между шагами оставил бы студента вообще без группы.
--
-- Пример: студент 202 (Новик Максим) из СДП-ПИ-241 (группа 2) в ЗФК-ПИ-241 (группа 8).
--
-- Уровень изоляции: REPEATABLE READ.
-- Транзакция изменяет конкретные строки (членство студента в группе, сам студент).
-- Все опасные ситуации здесь — это параллельные изменения тех же строк, а их REPEATABLE
-- READ обнаруживает: вторая транзакция получает ошибку сериализации вместо того, чтобы
-- молча затереть чужие изменения. Решений по агрегатам нет, поэтому SERIALIZABLE не нужен
-- (он дал бы лишние откаты), а READ COMMITTED недостаточно.
--
-- Опасные ситуации при READ COMMITTED:
-- 1) Двойной перевод. Два сотрудника деканата одновременно переводят одного студента:
--    один в ЗФК-ПИ-241, другой — в СДП-ИНФ-241. Вторая транзакция ждёт первую, её DELETE
--    удаляет уже 0 строк, INSERT проходит — студент оказывается сразу в двух группах.
--    На REPEATABLE READ вторая получает «could not serialize access due to concurrent delete».
--    (В нашем коде это дополнительно ловит проверка IF NOT FOUND после DELETE.)
-- 2) Потерянное обновление. Одновременно бухгалтерия по приказу возвращает студента на
--    бюджет (UPDATE FundingTypeID = 1). Наша транзакция, закончив позже, молча затирает это
--    значение на «Платное». На REPEATABLE READ — ошибка сериализации, конфликт виден.
-- 3) Проверка по устаревшим данным. Мы проверили, что курс новой группы совпадает, а
--    параллельно группу перевели на следующий курс (UPDATE StudyYear). На READ COMMITTED
--    следующие шаги видят уже новые данные, хотя проверка была по старым; на REPEATABLE
--    READ вся транзакция работает с одним снимком базы.
-- (Грязное чтение — отчёт видит студента ни в одной группе посреди перевода — возможно
-- только на READ UNCOMMITTED; в PostgreSQL этот уровень работает как READ COMMITTED.)

BEGIN;
SET TRANSACTION ISOLATION LEVEL REPEATABLE READ;

DO $$
DECLARE
  student_id CONSTANT integer := 202;
  old_group  CONSTANT integer := 2;   -- СДП-ПИ-241, дневная
  new_group  CONSTANT integer := 8;   -- ЗФК-ПИ-241, заочная
BEGIN
  -- проверки
  IF NOT EXISTS (SELECT 1 FROM "Group" o JOIN "Group" n
                   ON n."SpecialtyID" = o."SpecialtyID" AND n."StudyYear" = o."StudyYear"
                 WHERE o."ID" = old_group AND n."ID" = new_group) THEN
    RAISE EXCEPTION 'Группа % другой специальности или курса', new_group;
  END IF;

  -- перевод
  DELETE FROM "StudentGroup" WHERE "StudentID" = student_id AND "GroupID" = old_group;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Студент % не числится в группе %', student_id, old_group;
  END IF;

  INSERT INTO "StudentGroup" ("StudentID", "GroupID") VALUES (student_id, new_group);

  UPDATE "Student"
  SET "FundingTypeID" = (SELECT "ID" FROM "FundingType" WHERE "Type" = 'Платное')
  WHERE "StudentID" = student_id;
END $$;

-- проверка результата внутри транзакции
SELECT s."StudentID", s."LastName", g."Name" AS group_name, f."Type" AS funding
FROM "Student" s
JOIN "StudentGroup" sg ON sg."StudentID" = s."StudentID"
JOIN "Group" g ON g."ID" = sg."GroupID"
JOIN "FundingType" f ON f."ID" = s."FundingTypeID"
WHERE s."StudentID" = 202;

COMMIT;
